"""Generated, minified, and vendored path classification (DG1, D4)."""

from __future__ import annotations

import re
from enum import StrEnum
from typing import Final

from typing_extensions import TypedDict

from mergecraft.review_policy.manifest_names import GENERATOR_CONFIG_NAMES
from mergecraft.review_policy.paths import normalize_repo_path


class FileKind(StrEnum):
    """How a path should be treated for review policy."""

    SOURCE = "source"
    GENERATED = "generated"
    MINIFIED = "minified"
    VENDORED = "vendored"


class ChangeSet(TypedDict, total=False):
    """Side-effect-free change payload for inclusion policy."""

    changed_paths: list[str]
    diff_stats: dict[str, object]


def classify_path(path: str) -> FileKind:
    """Label a repository path as source, generated, minified, or vendored.

    ``generated``, ``vendor`` and ``third_party`` count only as directory
    segments, never as the file's own name, so ``bin/generated`` is source.
    The label is name-only; :func:`has_generated_marker` is the content check a
    caller needs before treating a ``generated/`` file as generated output.
    """
    normalized = normalize_repo_path(path).casefold()
    segments = normalized.split("/")
    name, directories = segments[-1], set(segments[:-1])
    if name.endswith((".min.js", ".min.css")):
        return FileKind.MINIFIED
    if "generated" in directories:
        return FileKind.GENERATED
    if directories & {"vendor", "third_party"}:
        return FileKind.VENDORED
    return FileKind.SOURCE


_GENERATED_MARKER: Final[re.Pattern[str]] = re.compile(
    r"@generated\b|do not edit|code generated|auto-?generated",
    re.IGNORECASE,
)
_MARKER_HEAD_LINES: Final[int] = 20


def has_generated_marker(text: str) -> bool:
    """Whether ``text`` carries a generated-file marker in its first lines.

    Generators state it at the top of the file: Go's ``Code generated … DO NOT
    EDIT``, ``@generated`` and ``auto-generated``. Only the first
    :data:`_MARKER_HEAD_LINES` lines are read, so a marker quoted deep in
    hand-written code does not count.

    Examples:
        >>> has_generated_marker("// Code generated by mockgen. DO NOT EDIT.\\n")
        True
        >>> has_generated_marker("x = 1\\n")
        False
    """
    head = "\n".join(text.split("\n", _MARKER_HEAD_LINES)[:_MARKER_HEAD_LINES])
    return _GENERATED_MARKER.search(head) is not None


def _generator_config_changed(change: ChangeSet) -> bool:
    changed = {normalize_repo_path(item) for item in change.get("changed_paths", [])}
    return any(item.rsplit("/", 1)[-1] in GENERATOR_CONFIG_NAMES for item in changed)


def finding_survives_generated_policy(path: str, *, change: ChangeSet) -> bool:
    """Return whether findings on ``path`` survive post-diff generated filtering (D4).

    Ignores the ``path in changed`` shortcut for generated/minified/vendored paths —
    callers already scoped findings to the diff.
    """
    kind = classify_path(path)
    if kind == FileKind.SOURCE:
        return True
    if kind == FileKind.GENERATED:
        return _generator_config_changed(change)
    return False


