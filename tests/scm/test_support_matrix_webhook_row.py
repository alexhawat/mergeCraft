"""The generated support matrix advertises no webhook ingress for any SCM.

Webhook deliveries were authenticated but processed by nothing, so the SCM axis
must stop advertising an ingress role. The surviving supported surface — GitHub
review support and the other axes — stays listed.
"""

from __future__ import annotations

import importlib.util
import sys

from tests.ci.workflow_support import REPO_ROOT

_GENERATOR = REPO_ROOT / "scripts" / "gen_support_matrix.py"
_COMMITTED = REPO_ROOT / "docs" / "support-matrix.md"


def _load_generator() -> object:
    spec = importlib.util.spec_from_file_location("gen_support_matrix_under_test", _GENERATOR)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _scm_rows(markdown: str) -> list[list[str]]:
    """Return the data rows of the ``## SCM`` table as stripped cell lists."""
    rows: list[list[str]] = []
    in_scm = False
    for line in markdown.splitlines():
        if line.startswith("## "):
            in_scm = line.strip() == "## SCM"
            continue
        if not in_scm or not line.startswith("|"):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if set("".join(cells)) <= set("-: "):
            continue
        if cells and cells[0].casefold() == "scm":
            continue
        rows.append(cells)
    return rows


def test_generated_matrix_advertises_no_webhook_ingress() -> None:
    """No SCM row names a webhook role; GitHub review support stays advertised."""
    generator = _load_generator()
    markdown = generator.gen_support_matrix()
    rows = _scm_rows(markdown)
    assert rows, "the SCM axis must still list its providers"
    for cells in rows:
        assert "webhook" not in " ".join(cells).casefold(), cells
    # Surviving surface: GitHub review support is still advertised.
    github = [cells for cells in rows if cells[0].strip("`") == "github"]
    assert github, rows
    assert "supported" in github[0][-1].casefold()


def test_committed_matrix_advertises_no_webhook_ingress() -> None:
    """The checked-in page, regenerated by ``make docs``, carries no webhook row."""
    markdown = _COMMITTED.read_text(encoding="utf-8")
    rows = _scm_rows(markdown)
    assert rows, "the SCM axis must still list its providers"
    for cells in rows:
        assert "webhook" not in " ".join(cells).casefold(), cells
    # Surviving surface: the other support axes are still rendered.
    for section in ("## OS", "## Languages", "## Analyzers", "## Providers", "## Models"):
        assert section in markdown
