"""A ``generated`` directory name alone is not proof a file is generated (#1309).

The default review ignore set still drops minified bundles, lockfiles and
changelogs, but a file under a ``generated/`` directory is reviewed unless the
operator opts the directory out with ``review.ignorePaths``. The fast-path
``generated`` recognizer needs a generated-file marker in the head text of every
such file, and never skips a mode-only or binary change. ``generated`` matches a
directory segment only, never a file of that name.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

import pytest

if TYPE_CHECKING:
    from mergecraft.review_policy.ignore_paths import ReviewIgnore

_MARKED = "# Code generated by protoc-gen-py. DO NOT EDIT.\na = 2\n"
_UNMARKED = "a = 2\n"


def _diff(path: str) -> str:
    return (
        f"diff --git a/{path} b/{path}\n--- a/{path}\n+++ b/{path}\n"
        "@@ -2,1 +2,1 @@\n-a = 1\n+a = 2\n"
    )


def _default_ignore() -> ReviewIgnore:
    from mergecraft.config.settings import ReviewSettings
    from mergecraft.review_policy.ignore_paths import build_review_ignore

    return build_review_ignore(input_value=None, review=ReviewSettings(), source="test")


@pytest.mark.parametrize(
    "path",
    ["src/generated/handler.py", "api/Generated/Auth.java", "bin/generated"],
    ids=["generated-dir", "generated-dir-mixed-case", "file-named-generated"],
)
def test_a_generated_directory_is_reviewed_by_default(path: str) -> None:
    ignore = _default_ignore()

    assert ignore.is_ignored(path) is False


@pytest.mark.parametrize(
    "path",
    ["web/static/app.min.js", "uv.lock", "package-lock.json", "CHANGELOG.md"],
    ids=["minified", "uv-lock", "package-lock", "changelog"],
)
def test_the_other_defaults_still_apply(path: str) -> None:
    ignore = _default_ignore()

    assert ignore.is_ignored(path) is True


def test_a_generated_directory_can_be_opted_out_with_ignore_paths() -> None:
    from mergecraft.config.settings import ReviewSettings
    from mergecraft.review_policy.ignore_paths import build_review_ignore

    review = ReviewSettings.model_validate({"ignorePaths": ["**/generated/**"]})
    ignore = build_review_ignore(input_value=None, review=review, source="test")

    assert ignore.is_ignored("src/generated/handler.py") is True


def test_generated_is_a_directory_segment_only() -> None:
    from mergecraft.classify.generated_files import FileKind, classify_path

    assert classify_path("bin/generated") == FileKind.SOURCE
    assert classify_path("generated") == FileKind.SOURCE
    assert classify_path("generated/x.py") == FileKind.GENERATED
    assert classify_path("lib/vendor") == FileKind.SOURCE


@pytest.mark.parametrize(
    "text",
    [
        "// Code generated by mockgen. DO NOT EDIT.\n",
        "# @generated by tooling\n",
        "/* This file is auto-generated. */\n",
    ],
    ids=["go-style", "at-generated", "auto-generated"],
)
def test_generated_markers_are_recognised(text: str) -> None:
    from mergecraft.classify.generated_files import has_generated_marker

    assert has_generated_marker(text)


def test_plain_source_has_no_generated_marker() -> None:
    from mergecraft.classify.generated_files import has_generated_marker

    assert not has_generated_marker("def handler():\n    return 1\n")


def _tier(diff: str, head_files: dict[str, str]) -> str:
    from mergecraft.classify.triage import triage_diff
    from mergecraft.config.settings import FastPathSettings

    config = FastPathSettings.model_validate({"enabled": True, "skipLlm": ["generated"]})
    return triage_diff(diff, config=config, head_files=head_files).tier


def test_a_marked_generated_file_skips() -> None:
    path = "pkg/generated/api.py"

    assert _tier(_diff(path), {path: _MARKED}) == "skip"


@pytest.mark.parametrize(
    "head_files",
    [{}, {"pkg/generated/api.py": _UNMARKED}],
    ids=["no-head-text", "no-marker"],
)
def test_a_generated_directory_without_a_marker_is_full(head_files: dict[str, str]) -> None:
    assert _tier(_diff("pkg/generated/api.py"), head_files) == "full"


def test_a_lockfile_alone_needs_no_marker() -> None:
    assert _tier(_diff("uv.lock"), {}) == "skip"


def test_a_mode_only_change_under_generated_is_full() -> None:
    path = "generated/run.sh"
    diff = f"diff --git a/{path} b/{path}\nold mode 100644\nnew mode 100755\n"

    assert _tier(diff, {path: _MARKED}) == "full"


def test_a_binary_change_under_generated_is_full() -> None:
    path = "generated/blob.bin"
    diff = (
        f"diff --git a/{path} b/{path}\nindex 1111111..2222222 100644\n"
        f"Binary files a/{path} and b/{path} differ\n"
    )

    assert _tier(diff, {path: _MARKED}) == "full"
